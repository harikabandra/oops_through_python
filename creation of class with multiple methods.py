class Demo():
    def add(self,a,b):
        print("Addition:",a+b)
        
    def sub(self,a,b):
        print("Subtraction:",a-b)
        
    def mul(self,a,b):
        print("multiplication:",a*b)
        
    def div(self,a,b):
        print("division:",a/b)
        
d1=Demo()

d1.add(0,1)
d1.sub(9,7)
d1.mul(3,1)
d1.div(20,5)